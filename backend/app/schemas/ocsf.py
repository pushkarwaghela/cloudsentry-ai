"""
CloudSentry AI - OCSF (Open Cybersecurity Schema Framework) Unified Schema
========================================================================

WHY OCSF?
In modern enterprise Security Operations Centers (SOC), multi-cloud environments
generate telemetry in radically different formats (e.g., AWS CloudTrail vs Azure Activity Log).
Without a standardized schema:
1. Detection rules must be rewritten for each cloud provider.
2. Machine Learning models require disparate feature pipelines per cloud.
3. SIEM storage costs balloon due to duplicate and unindexed fields.

This module normalizes raw multi-cloud events into a unified, vendor-neutral schema
modeled after OCSF v1.1.0/v1.2.0 (Open Cybersecurity Schema Framework), adopted by
AWS, Splunk, Elastic, CrowdStrike, and Palo Alto Networks.
"""

from datetime import datetime, timezone
from enum import Enum
from typing import Any, Dict, List, Optional
from uuid import uuid4
from pydantic import BaseModel, Field, ConfigDict


class CloudProvider(str, Enum):
    AWS = "aws"
    AZURE = "azure"
    GCP = "gcp"
    HYBRID = "hybrid"


class OCSFCategory(str, Enum):
    """
    OCSF High-Level Categories:
    - 1: System Activity
    - 2: Findings (Detections, Alerts, Vulnerabilities)
    - 3: Identity & Access Management (Authentication, Authorizations)
    - 4: Network Activity (NetFlow, VPC Logs, DNS)
    - 6: Application Activity (API calls, Cloud audit logs)
    """
    AUTHENTICATION = "authentication"          # OCSF Class 3001
    AUTHORIZATION = "authorization"            # OCSF Class 3002
    API_ACTIVITY = "api_activity"              # OCSF Class 6003 (Cloud Audit / Management)
    NETWORK_ACTIVITY = "network_activity"      # OCSF Class 4001 (VPC Flow Logs)
    SECURITY_FINDING = "security_finding"      # OCSF Class 2001 (GuardDuty, Defender)
    CONFIGURATION = "configuration"            # OCSF Class 1005 (Resource state / CSPM)


class EventSeverity(str, Enum):
    """Normalized security severity levels."""
    INFORMATIONAL = "INFORMATIONAL"  # 1
    LOW = "LOW"                      # 2
    MEDIUM = "MEDIUM"                # 3
    HIGH = "HIGH"                    # 4
    CRITICAL = "CRITICAL"            # 5


class EventStatus(str, Enum):
    SUCCESS = "SUCCESS"
    FAILURE = "FAILURE"
    DENIED = "DENIED"
    UNKNOWN = "UNKNOWN"


class GeoLocation(BaseModel):
    """Normalized geographic location of the network actor."""
    country: Optional[str] = "Unknown"
    country_code: Optional[str] = None
    city: Optional[str] = "Unknown"
    region: Optional[str] = None
    latitude: Optional[float] = None
    longitude: Optional[float] = None
    asn: Optional[int] = None
    isp: Optional[str] = None


class ActorIdentity(BaseModel):
    """
    Normalized identity of the user, service principal, or IAM role
    initiating the security event.
    """
    user_name: Optional[str] = "Unknown"
    user_id: Optional[str] = None
    email: Optional[str] = None
    account_id: Optional[str] = None       # AWS Account ID or Azure Subscription ID
    tenant_id: Optional[str] = None        # Azure Tenant ID or AWS Org ID
    principal_type: Optional[str] = None   # IAMUser, AssumedRole, ServicePrincipal, FederatedUser
    session_issuer: Optional[str] = None   # Role assumed, if any


class NetworkEndpoint(BaseModel):
    """Normalized source or destination network endpoint."""
    ip: Optional[str] = None
    port: Optional[int] = None
    domain: Optional[str] = None
    geo: Optional[GeoLocation] = None
    interface_id: Optional[str] = None


class TargetResource(BaseModel):
    """The cloud resource acted upon (e.g. S3 Bucket, IAM Role, Azure KeyVault, VM)."""
    resource_type: str                     # e.g., "s3_bucket", "iam_role", "storage_account"
    resource_id: Optional[str] = None      # ARN or Azure Resource ID
    resource_name: Optional[str] = None    # Friendly name
    region: Optional[str] = None           # us-east-1, eastus
    details: Dict[str, Any] = Field(default_factory=dict)


class SecurityFindingMetadata(BaseModel):
    """Metadata specific to alerts generated by upstream security scanners."""
    finding_id: Optional[str] = None
    scanner_name: Optional[str] = None     # "GuardDuty", "Defender for Cloud"
    finding_type: Optional[str] = None     # e.g., "UnauthorizedAccess:IAMUser/InstanceCredentialExfiltration"
    title: Optional[str] = None
    description: Optional[str] = None
    remediation_steps: Optional[str] = None


class UnifiedOCSFEvent(BaseModel):
    """
    Unified Open Cybersecurity Schema Framework (OCSF) Event.
    Every raw log from AWS (CloudTrail, GuardDuty, VPC Flow) or
    Azure (Activity, Entra ID, Defender) is mapped into this model.
    """
    # Unique Event Identification
    event_id: str = Field(default_factory=lambda: str(uuid4()))
    timestamp: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
    ingestion_timestamp: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))

    # Cloud Provider & Origin
    cloud_provider: CloudProvider
    source_service: str                    # "cloudtrail", "guardduty", "vpc_flow", "azure_ad", "activity_log", "defender"
    original_event_name: str               # e.g., "ConsoleLogin", "Microsoft.Authorization/roleAssignments/write"

    # Categorization & Classification
    category: OCSFCategory
    severity: EventSeverity = EventSeverity.INFORMATIONAL
    status: EventStatus = EventStatus.SUCCESS
    status_code: Optional[str] = None      # HTTP status code or API error code
    status_detail: Optional[str] = None    # "AccessDenied", "MFA required", etc.

    # Actor & Network
    actor: ActorIdentity = Field(default_factory=ActorIdentity)
    src_endpoint: Optional[NetworkEndpoint] = None
    dst_endpoint: Optional[NetworkEndpoint] = None
    user_agent: Optional[str] = None

    # Target & Action
    action: str                            # Normalized verb: "LOGIN", "ASSUME_ROLE", "PUT_POLICY", "FLOW_ACCEPT"
    target: Optional[TargetResource] = None

    # Network Flow Specifics (if applicable)
    bytes_transferred: Optional[int] = None
    packets_transferred: Optional[int] = None
    protocol: Optional[str] = None

    # Finding Specifics (if alert/finding)
    finding_metadata: Optional[SecurityFindingMetadata] = None

    # Forensics & AI Enrichment
    raw_log: Dict[str, Any] = Field(default_factory=dict)
    anomaly_score: Optional[float] = None  # Populated by ML Detection Engine (0.0 to 100.0)
    risk_score: Optional[float] = None     # Blended score (0.0 to 100.0)
    is_anomaly: bool = False
    tags: List[str] = Field(default_factory=list)

    model_config = ConfigDict(populate_by_name=True)
