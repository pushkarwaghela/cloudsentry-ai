"""
CloudSentry AI - LLM Alert Triage & MITRE ATT&CK Schemas
========================================================

WHY HIGH-STRUCTURED TRIAGE MATTERS IN A MODERN SOC:
Unstructured text from LLMs cannot be ingested by SOAR tools (e.g., Splunk SOAR,
Cortex XSOAR, Azure Logic Apps) and causes hallucination risks in high-pressure
security operations.

These Pydantic schemas enforce rigid typing for:
- MITRE ATT&CK Tactic, Technique, and Sub-technique IDs
- Actionable containment commands (AWS CLI, Azure CLI, PowerShell)
- Calibrated confidence and severity scoring
"""

from datetime import datetime, timezone
from enum import Enum
from typing import Any, Dict, List, Optional
from uuid import uuid4
from pydantic import BaseModel, Field, ConfigDict


class TriageVerdict(str, Enum):
    TRUE_POSITIVE_MALICIOUS = "TRUE_POSITIVE_MALICIOUS"
    SUSPICIOUS_INVESTIGATION_REQUIRED = "SUSPICIOUS_INVESTIGATION_REQUIRED"
    FALSE_POSITIVE_BENIGN = "FALSE_POSITIVE_BENIGN"


class MitreAttackMapping(BaseModel):
    """Normalized MITRE ATT&CK for Cloud matrix mapping."""
    tactic: str                          # e.g., "Privilege Escalation", "Credential Access", "Exfiltration"
    technique_id: str                    # e.g., "T1098.003", "T1078.004", "T1530"
    technique_name: str                  # e.g., "Account Manipulation: Additional Cloud Roles"
    sub_technique: Optional[str] = None
    reference_url: str                   # e.g., "https://attack.mitre.org/techniques/T1098/003/"


class ContainmentStep(BaseModel):
    """Immediate tactical mitigation step for the on-duty SOC tier 1/2 analyst."""
    order: int
    title: str                           # Short action summary
    action_type: str                     # "IAM_REVOCATION", "NETWORK_ISOLATION", "PASSWORD_RESET", "FORENSIC_SNAPSHOT"
    command: Optional[str] = None        # Exact CLI command string
    rationale: str                       # Why this halts the adversary's blast radius


class AlertTriageReport(BaseModel):
    """
    Complete structured incident triage generated by the AI / LLM pipeline.
    """
    triage_id: str = Field(default_factory=lambda: str(uuid4()))
    event_id: str
    created_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))

    # Incident Overview
    incident_title: str
    executive_summary: str
    triage_verdict: TriageVerdict
    recommended_severity: str            # "CRITICAL", "HIGH", "MEDIUM", "LOW"
    confidence_score: float = 0.95       # 0.0 to 1.0
    confidence_rationale: str

    # Framework Alignment
    mitre_attack: List[MitreAttackMapping] = Field(default_factory=list)

    # Actionable Response
    containment_playbook: List[ContainmentStep] = Field(default_factory=list)

    # Model Telemetry
    llm_provider: str                    # "deterministic_expert", "ollama_llama3", "openai", "groq", "gemini"
    inference_time_ms: float = 0.0

    model_config = ConfigDict(populate_by_name=True)
